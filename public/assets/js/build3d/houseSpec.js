/* ─────────────────────────  кровля  ───────────────────────── */

export const RIDGE_Z = DEPTH / 2; // конёк ровно посередине глубины
// 5.33 давало уклон 20° и отношение сторон 4.4 : 1 — на общем плане дом
// превращался в тонкую полоску. При 5.7 уклон ≈ 24°, отношение 4.1 : 1:
// силуэт остаётся горизонтальным, но кровля начинает в нём участвовать.
export const RIDGE_Y = 5.7;
export const RIDGE_RISE = RIDGE_Y - WALL_TOP;

export const OVERHANG_EAVE = 1.0; // свес по карнизу
export const OVERHANG_GABLE = 0.3; // свес по фронтону: больше нельзя, иначе
// он нависнет над рамой портала и съест её
export const ROOF_T = 0.18; // толщина кровельного пирога

export const ROOF_HALF_RUN = RIDGE_Z + OVERHANG_EAVE;
export const ROOF_ANGLE = Math.atan2(RIDGE_RISE, ROOF_HALF_RUN); // ≈ 20°
export const ROOF_SLOPE_LENGTH = Math.hypot(ROOF_HALF_RUN, RIDGE_RISE);

export const ROOF_X0 = -OVERHANG_GABLE;
export const ROOF_X1 = TOTAL_X1 + OVERHANG_GABLE;

/** Высота нижней плоскости ската над заданной точкой по оси Z. */
export function roofPlaneAt(z) {
  return RIDGE_Y - (RIDGE_RISE * Math.abs(z - RIDGE_Z)) / ROOF_HALF_RUN;
}

/* ─────────────────────────  каркас  ─────────────────────────
 *
 * Шаги стоек и стропил заданы здесь, а не в геометрии: на этапе каркаса
 * именно они читаются как «настоящая стройка», и их придётся подбирать
 * по кадру, а не по строительным нормам.
 */

export const STUD_PITCH = 0.6; // шаг стоек, он же шаг доски обшивки × 2
export const STUD_W = 0.1;
/**
 * Толщина самого каркаса. Стена в 0.24 — это 200 мм каркаса плюс обшивка по
 * 20 мм с каждой стороны, поэтому все элементы каркаса обязаны быть уже
 * стены. Пока они строились в полную толщину, их грани совпадали с гранями
 * обшивки, и на каждом пикселе видеокарта выбирала между ними произвольно —
 * стены покрывались зигзагом.
 */
export const FRAME_T = 0.2;
export const PLATE_H = 0.15; // высота обвязки
export const RAFTER_PITCH = 0.9;
export const RAFTER_W = 0.08;
export const RAFTER_H = 0.22;
export const RAFTER_INSET = 0.2; // отступ крайнего стропила от торца кровли
export const MULLION = 0.08; // импост панорамного остекления

/**
 * Ось стропила ниже плоскости ската на половину сечения по вертикали:
 * 0.22 / 2 / cos 23.7° = 0.1201. Значение оставлено округлённым до 0.12, потому
 * что стропила уже построены с ним, а узел подвеса обязан сесть ровно в них.
 * Разводить два источника одной отметки нельзя — разойдутся на первой правке.
 */
export const RAFTER_AXIS_DROP = 0.12;

/** Отметка оси стропила над точкой z. */
export function rafterAxisAt(z) {
  return roofPlaneAt(z) - RAFTER_AXIS_DROP;
}

/** Отметка низа стропила над точкой z — к нему подшивается потолок террасы. */
export function rafterUnderAt(z) {
  return rafterAxisAt(z) - RAFTER_H / 2 / Math.cos(ROOF_ANGLE);
}

/** Оси стропил по длине дома. Один источник для кровли и для узлов подвеса. */
export function rafterPositions() {
  return spread(
    RAFTER_INSET,
    TOTAL_X1 - RAFTER_INSET,
    Math.round(TOTAL_X1 / RAFTER_PITCH),
  );
}

