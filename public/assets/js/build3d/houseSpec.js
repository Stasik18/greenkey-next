/** Шаг свайного поля. Сваи ставятся по осям стен и под террасой. */
export const PILE_GRID = { stepX: 2.25, stepZ: 3.6, inset: 0.4 };

export function pilePositions() {
  const out = [];
  const xs = spread(
    PILE_GRID.inset,
    TOTAL_X1 - PILE_GRID.inset,
    Math.round(TOTAL_X1 / PILE_GRID.stepX) + 1,
  );
  const zs = spread(
    PILE_GRID.inset,
    DEPTH - PILE_GRID.inset,
    Math.round(DEPTH / PILE_GRID.stepZ) + 1,
  );
  for (const z of zs) for (const x of xs) out.push([x, z]);
  return out;
}

