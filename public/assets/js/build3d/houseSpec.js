/** Равномерные позиции от `from` до `to` включительно. */
export function spread(from, to, count) {
  if (count <= 1) return [(from + to) / 2];
  const values = [];
  const gap = (to - from) / (count - 1);
  for (let i = 0; i < count; i++) values.push(from + gap * i);
  return values;
}

/**
 * Вычитает проёмы из прямоугольной грани и возвращает сплошные участки стены.
 *
 * Грань режется горизонтальными полосами по границам проёмов, внутри каждой
 * полосы остаток набирается слева направо. Стена получается точной и при этом
 * целиком состоит из прямоугольников, а значит вся укладывается в один
 * InstancedMesh — это и позволит держать кадр на мобильных.
 */
export function subtractOpenings(width, height, openings) {
  const EPS = 1e-4;
  const cuts = new Set([0, height]);
  for (const o of openings) {
    cuts.add(clamp(o.v0, 0, height));
    cuts.add(clamp(o.v1, 0, height));
  }

  const levels = [...cuts].sort((a, b) => a - b);
  const rects = [];

  for (let i = 0; i < levels.length - 1; i++) {
    const y0 = levels[i];
    const y1 = levels[i + 1];
    if (y1 - y0 < EPS) continue;

    const band = openings
      .filter((o) => o.v0 <= y0 + EPS && o.v1 >= y1 - EPS)
      .sort((a, b) => a.u0 - b.u0);

    let cursor = 0;
    for (const o of band) {
      const start = clamp(o.u0, 0, width);
      if (start - cursor > EPS)
        rects.push({ u: cursor, v: y0, w: start - cursor, h: y1 - y0 });
      cursor = Math.max(cursor, clamp(o.u1, 0, width));
    }
    if (width - cursor > EPS)
      rects.push({ u: cursor, v: y0, w: width - cursor, h: y1 - y0 });
  }

  return rects;
}

function clamp(value, min, max) {
  return value < min ? min : value > max ? max : value;
}

