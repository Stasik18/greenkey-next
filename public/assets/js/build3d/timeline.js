/**
 * Связь прокрутки со сценой: ОДИН ЖЕСТ — ОДИН ЭТАП.
 *
 * Решение владельца от 2026-08-05. Прежде блок шёл сплошной прокруткой: доля
 * тянулась за позицией страницы, и читатель мог остановиться в любой точке,
 * в том числе посреди монтажа. Отсюда и жалоба на рывки, которая пережила все
 * четыре правки этапа F.
 *
 * ПОЧЕМУ ЭТО ЛЕЧИТ ИМЕННО РЫВКИ, А НЕ ПРОСТО МЕНЯЕТ ПОВЕДЕНИЕ. Сглаживание в
 * блоке существовало ровно затем, чтобы гасить неровный ввод: колесо даёт
 * ступени по 100 px, тачпад — россыпь по 6 px, и без фильтра сцена шла бы
 * рывками вслед за рукой. Но фильтр по построению означает, что картинка не
 * совпадает с рукой: она догоняет. Когда шаг ведёт страница сама, гасить
 * нечего — ход задан твином, он ровный по определению, и сглаживание снято
 * целиком. Это не настройка коэффициента, а исчезновение самой причины.
 *
 * ИСТОЧНИК ВРЕМЕНИ ОСТАЛСЯ ОДИН — положение страницы. Оно по-прежнему
 * единственное состояние: обновление, кнопка «назад», перетаскивание ползунка и
 * приход по якорю работают сами собой, а сцена остаётся чистой функцией доли.
 * Изменилось только то, КТО двигает позицию: раньше рука напрямую, теперь твин
 * по жесту руки.
 */

import {
  applyGroups,
  activeStageIndex,
  STAGES,
  SCENE_SETTLED,
} from "./stages.js";

/**
 * Сколько длится проход блока по всем десяти шагам, в секундах.
 *
 * Это ЕДИНСТВЕННОЕ назначенное число во всей длительности; остальное выводится
 * из сценария. Взято равным прежнему проходу (десять шагов по 0.9 с), чтобы
 * правка меняла ритм, а не цену: читатель тратит на блок столько же.
 */
const PASS_SECONDS = 9;

/**
 * Границы длительности одного шага. Только предохранитель: при нынешнем
 * сценарии связывает единственный такт — первый, самый короткий.
 */
const STEP_MIN = 0.6;
const STEP_MAX = 1.5;

/**
 * Тишина после жеста, по которой шаг считается законченным.
 *
 * Нужна из-за тачпада: одно движение пальца даёт до шестидесяти событий в
 * секунду, и без этого один мах прошёл бы половину блока. Замер на записи
 * владельца (`input-capture.html`): тачпад 595 событий за 10 с, то есть 59.5 Гц
 * — интервал между событиями около 17 мс. Колесо мыши даёт 1 событие в секунду.
 * Порог 220 мс лежит между ними с запасом больше чем на порядок.
 */
const QUIET_MS = 220;

/** Порог свайпа. Ниже — читатель просто держит палец на экране. */
const TOUCH_THRESHOLD = 40;

/**
 * Ступень, ниже которой событие считается частью маха, а не отдельным щелчком.
 *
 * Число не выбрано, а взято из записи владельца (`input-capture.html`): тачпад
 * даёт шаг медианой 6 px и максимумом 39, колесо мыши — ровно 100 px, все
 * события кратны 120 в `wheelDelta`. Между 39 и 100 пусто, порог стоит
 * посередине этой пустоты. Тот же порог был выведен для классификатора ввода.
 */
const WHEEL_NOTCH = 60;

/**
 * ТОЧКИ ПОКОЯ — начало выдержки каждого этапа: первый кадр, на котором этап
 * закончен, дом собран и камера пришла на место.
 *
 * У последнего этапа точка покоя стоит ПОЗЖЕ его выдержки, и это не мелочь:
 * собственный свет террасы разгорается ПОСЛЕ `enterEnd` десятого такта.
 * Останови мы читателя на `enterEnd` — он никогда не увидел бы включённую
 * ленту, то есть ровно тот кадр, ради которого блок и заканчивается вечером.
 *
 * НО И НЕ ДО КОНЦА БЛОКА. Первым заходом здесь стояла единица, и последний шаг
 * треть своей длительности доигрывал по неподвижной картинке, держа ввод
 * запертым: между `SCENE_SETTLED` и единицей меняться уже нечему. Теперь шаг
 * кончается там, где кончается сцена, а оставшиеся 372 px читатель проходит
 * родной прокруткой — то есть выезжает из блока с ходу, а не в стену.
 */
const REST = STAGES.map((stage, i) =>
  i === STAGES.length - 1 ? SCENE_SETTLED : stage.enterEnd,
);

/** Начало выхода этапа: отсюда идёт его сборка. */
const EXIT_START = STAGES.map((stage) => stage.progressStart);

/** Допуск, внутри которого доля считается стоящей на точке покоя. */
const AT_REST = 1e-3;

/** Длина каждого шага в долях прокрутки: от начала выхода до точки покоя. */
const SPANS = REST.map((rest, i) => rest - EXIT_START[i]);
const SPAN_TOTAL = SPANS.reduce((a, b) => a + b, 0);

/**
 * ДЛИТЕЛЬНОСТЬ ШАГА ВЫВЕДЕНА ИЗ СЦЕНАРИЯ, А НЕ НАЗНАЧЕНА.
 *
 * Решение владельца от 2026-08-05: «сделай длительность шага по объёму этапа».
 *
 * Прежде на все десять шагов стояло одно число 0.9 с, а комментарий уверял, что
 * разницу в объёме гасит камера. Это неправда: `buildPace` в `camera.js`
 * выравнивает ход ВНУТРИ такта — он делит накопленный экранный путь на
 * собственный итог такта и итог выбрасывает. Между тактами не выравнивается
 * ничего. Замер экранного хода: при одинаковых 0.9 с скорость картинки на
 * разных этапах расходилась примерно ВТРОЕ, от 200 до 580 px/с. То есть
 * неровность, изгнанная из такта, вернулась на границах между тактами.
 *
 * Теперь каждый шаг получает время ПРОПОРЦИОНАЛЬНО своей длине в сценарии.
 * Основой взята длина такта у самого сценария, а не экранный путь камеры, и это
 * важно по двум причинам. Первая: доли тактов — это ритм, который владелец
 * принимал по превью, он уже утверждён и уже лежит в `stages.js` единственным
 * источником. Вторая: у первого такта камера не двигается ВОВСЕ (обноска
 * появляется при неподвижном кадре), и по экранному пути он получил бы нулевую
 * длительность.
 *
 * Проще говоря: блок играет утверждённый сценарий целиком, только вчетверо
 * быстрее — пропорции сохранены все до одной.
 *
 * Что выходит при нынешнем сценарии (48.8 с оригинала → 9 с прохода):
 *
 *   такт   01    02    03    04    05    06    07    08    09    10
 *   ориг.  2.0   4.2   2.4   2.8   3.4   3.4   3.2   4.2   2.4   5.0
 *   шаг    0.60  1.15  0.65  0.76  0.93  0.93  0.87  1.15  0.65  1.36
 */
const STEP_SECONDS = SPANS.map((span) =>
  Math.min(STEP_MAX, Math.max(STEP_MIN, (PASS_SECONDS * span) / SPAN_TOTAL)),
);

export function createTimeline({
  gsap,
  ScrollTrigger,
  section,
  house,
  cameraRig,
  textSync,
}) {
  gsap.registerPlugin(ScrollTrigger);

  // На мобильных показ и скрытие адресной строки меняют высоту окна и без
  // этого пересчитывали бы границы секции прямо под пальцем.
  ScrollTrigger.config({ ignoreMobileResize: true });

  const state = { progress: 0 };
  const root = document.documentElement;
  let lastAppliedIndex = -1;
  let lastAppliedProgress = -1;

  /*
   * ГРУППА ТРОГАЕТСЯ, ТОЛЬКО ЕСЛИ ЕЁ ДОЛЯ ДЕЙСТВИТЕЛЬНО ИЗМЕНИЛАСЬ, и это не
   * микрооптимизация, а причина рывков.
   *
   * Раньше признак «дом изменился» выводился из того, сдвинулась ли ПРОКРУТКА, а
   * она сдвигается на каждом кадре движения. По этому признаку страница
   * пересчитывала теневую карту, и она пересчитывалась даже там, где дом стоит:
   * на выдержках такта и вообще всюду, где едет одна камера. От камеры теневая
   * карта не зависит вовсе — солнце направленное, его теневая камера привязана к
   * солнцу, а не к зрителю.
   *
   * Цена этой ошибки замерена контролируемо: пересчёт карты стоит около 3 мс, и
   * получал их каждый кадр прокрутки. Проваленный кадр читается именно рывком:
   * за долгий кадр шаг продвигается СИЛЬНЕЕ, поэтому картинка прыгает скачком.
   *
   * Заодно перестала трогаться и сама геометрия: `setGroupProgress` обходит всех
   * детей группы, а их до сотни, и звать его с тем же числом незачем.
   */
  const applied = new Map();
  let houseChanged = false;
  const setGroup = (name, value) => {
    if (applied.get(name) === value) return;
    applied.set(name, value);
    house.setGroupProgress(name, value);
    houseChanged = true;
  };

  /*
   * Обе переменные объявлены ДО создания триггера: `ScrollTrigger.create`
   * обновляется сразу и зовёт `onUpdate` синхронно, а обращение к `let` выше по
   * файлу — не мягкая ошибка, а падение на загрузке.
   */
  /** Идущий шаг или null. Пока он есть, ввод не принимается вовсе. */
  let шаг = null;
  /** Время последнего события ввода, которое мы перехватили. */
  let последнийВвод = 0;
  /** Направление жеста, пришедшего посреди шага, или 0. Глубина очереди — один. */
  let очередь = 0;
  /**
   * Куда читатель шёл последним жестом: 1 — вниз, −1 — вверх, 0 — ещё не ходил.
   * Из этого выводится сторона выхода из блока; разбор ниже, у самой кнопки.
   * Объявлено здесь, вместе с остальным состоянием: обращаются к нему сверху.
   */
  let ходБыл = 0;

  /*
   * Кнопка выхода берётся ДО создания триггера: `ScrollTrigger.create`
   * обновляется сразу и синхронно зовёт `onUpdate`, а тот трогает эти же
   * значения. Объявление ниже по файлу означало бы падение на загрузке.
   */
  const выход = section.querySelector(".build-skip");
  const стрелка = выход && выход.querySelector(".build-skip-arrow");
  /** Сторона, которая сейчас нарисована. Чтобы не трогать DOM без нужды. */
  let показано = 0;

  /*
   * ScrollTrigger здесь БЕЗ `scrub` и без твина: он остался только затем, чтобы
   * знать границы секции и текущую долю. Догоняющего твина, который раньше вёл
   * прогресс, больше нет — прогресс либо равен позиции страницы один в один,
   * либо его ведёт шаг.
   */
  const st = ScrollTrigger.create({
    trigger: section,
    start: "top top",
    end: "bottom bottom",
    invalidateOnRefresh: true,
    onUpdate: (self) => {
      if (!шаг) state.progress = self.progress;
      /*
       * Сторона выхода пересчитывается и на простой прокрутке, а не только на
       * жесте. Читатель, вошедший в блок снизу и ещё не сделавший ни одного
       * жеста, видел стрелку вниз — то есть кнопку, которая отправила бы его
       * туда, откуда он пришёл. Разметку это не дёргает: `показатьСторону`
       * молчит, пока сторона не сменилась.
       */
      показатьСторону();
    },
    // Шаг двигает позицию прокрутки программно, а CSS-правило
    // scroll-behavior:smooth накладывает на каждое такое движение своё
    // сглаживание — вместе они дают вязкий, иногда не сходящийся ход.
    // Плавность якорных ссылок при этом сохраняется вне блока.
    onToggle: (self) => {
      root.style.scrollBehavior = self.isActive ? "auto" : "";
    },
  });

  /* ─────────────────────────────  шаг  ───────────────────────────── */

  const позиция = (p) => st.start + p * (st.end - st.start);

  /**
   * Держит ли блок экран прямо сейчас.
   *
   * Считается по позиции, а не по `st.isActive`: пока страница стоит ровно на
   * начале секции — а это ровно тот случай, когда читатель только что подошёл к
   * блоку и делает первый жест, — свойство ещё не выставлено, и первый жест
   * уходил в пустоту.
   */
  function внутри() {
    const y = window.scrollY;
    return y >= st.start - 1 && y <= st.end + 1;
  }

  /** Номер точки покоя, на которой стоит читатель, или −1 до первой. */
  function текущая() {
    const p = state.progress;
    for (let i = REST.length - 1; i >= 0; i--) {
      if (p >= REST[i] - AT_REST) return i;
    }
    return -1;
  }

  /**
   * Куда ведёт следующий жест, или null — значит блок кончился и страницу надо
   * отпустить.
   *
   * ВЫДЕРЖКА ПРОХОДИТСЯ МГНОВЕННО, И ЭТО НЕ ВИДНО. Между точкой покоя этапа и
   * началом выхода следующего лежит его выдержка, где не меняется ничего: дом
   * собран, камера стоит. Анимировать её значило бы отдать треть каждого шага
   * неподвижной картинке — читатель прочёл бы это как заминку. Поэтому шаг
   * начинается с мгновенной установки доли на начало выхода: кадр там побитово
   * тот же, меняется только подпись, и меняется она ровно тогда, когда начинает
   * строиться новый этап.
   *
   * ЧИТАТЕЛЬ НЕ ОБЯЗАН СТОЯТЬ НА ТОЧКЕ ПОКОЯ. Он приходит по якорю, тянет
   * ползунок, обновляет страницу посреди блока — и оказывается в произвольной
   * доле. Тогда «назад» ведёт на ближайшую точку покоя ПОЗАДИ, а не через неё:
   * первым заходом шаг назад из середины этапа перепрыгивал сразу два.
   */
  function цель(направление) {
    const i = текущая();
    const p = state.progress;

    if (направление > 0) {
      const j = i + 1;
      if (j >= REST.length) return null;
      return { от: Math.max(p, EXIT_START[j]), до: REST[j], такт: j };
    }

    const наМесте = i >= 0 && Math.abs(p - REST[i]) < AT_REST;
    const j = наМесте ? i - 1 : i;
    if (j < 0) {
      /*
       * Стоя на точке покоя ПЕРВОГО этапа, читатель уходит не из блока, а на
       * его начало: жест назад обязан разобрать ровно то, что построил жест
       * вперёд. Иначе ход назад несимметричен ходу вперёд — первый жест вверх
       * выбрасывал из блока с уже построенным этапом.
       */
      if (наМесте && i === 0) return { от: p, до: EXIT_START[0], такт: 0 };
      return null;
    }

    /*
     * Назад этап разбирается тем же путём, каким собрался, и дальше выдержка
     * предыдущего проходится мгновенно — по той же причине, что и вперёд.
     *
     * Такт для длительности берётся РАЗБИРАЕМЫЙ, а не тот, на который придём:
     * ход назад — это тот же самый шаг, проигранный в обратную сторону, и время
     * ему положено то же.
     */
    const граница = EXIT_START[j + 1];
    return p > граница
      ? { от: p, до: граница, затем: REST[j], такт: j + 1 }
      : { от: p, до: REST[j], такт: j };
  }

  /**
   * Время на шаг: доля времени такта, пропорциональная пройденному куску.
   *
   * Кусок нужен потому, что шаг не всегда идёт от начала выхода до конца.
   * Читатель приходит по якорю или тянет ползунок и оказывается посреди этапа;
   * доигрывать оттуда полную длительность значило бы ползти вдвое медленнее
   * остальных. Скорость картинки при таком счёте одна и та же везде.
   *
   * Нижняя граница — чтобы совсем короткий остаток не срабатывал как прыжок:
   * рывок на четверть секунды заметнее, чем лишняя четверть секунды хода.
   */
  const МИН_ХОД = 0.25;

  function длительность(план, пройти) {
    const полная = STEP_SECONDS[план.такт];
    const весь = SPANS[план.такт];
    if (!(весь > 0)) return полная;
    return Math.max(МИН_ХОД, полная * Math.min(1, пройти / весь));
  }

  function шагнуть(направление) {
    const план = цель(направление);
    if (!план) return false;

    const пройти = Math.abs(план.до - план.от);
    if (пройти < AT_REST) {
      установить(план.затем !== undefined ? план.затем : план.до);
      return true;
    }

    установить(план.от);
    const поле = { p: план.от };
    шаг = gsap.to(поле, {
      p: план.до,
      duration: длительность(план, пройти),
      /*
       * Ход ЛИНЕЙНЫЙ, и это осознанно. Форму движения задаёт камера: внутри
       * выхода она идёт по кривой с полкой и ровно по экранному пути
       * (`camera.js`, решение владельца по вопросу 2). Своя кривая поверх неё
       * означала бы два сглаживания подряд — ровно та ошибка, которую уже
       * находили у камеры на этапе E.
       */
      ease: "none",
      onUpdate: () => установить(поле.p),
      onComplete: () => {
        шаг = null;
        if (план.затем !== undefined) установить(план.затем);
        // Жест, накопленный за время шага, берётся сразу — без него читатель,
        // который крутит не отрываясь, получал одну ступень и тишину.
        if (очередь) {
          const дальше = очередь;
          очередь = 0;
          шагнуть(дальше);
        }
      },
    });
    return true;
  }

  /*
   * МГНОВЕННОСТЬ ЗАДАЁТСЯ ЯВНО, А НЕ ЧЕРЕЗ СНЯТИЕ `scroll-behavior`.
   *
   * На странице стоит глобальное `html{scroll-behavior:smooth}`, и оно
   * накладывает СВОЁ сглаживание на каждый программный `scrollTo` — поверх
   * нашего шага. Прежде это гасилось инлайновым `auto`, который ставит
   * `onToggle` триггера. Но в самом начале блока — там, где читатель всегда и
   * начинает, — переключение ещё не произошло, инлайнового стиля нет, и первый
   * же переход уезжал плавной прокруткой браузера: замер показал разгон и
   * торможение на 550 мс вместо мгновенной установки.
   *
   * `behavior:'instant'` перебивает CSS независимо от порядка событий и ничего
   * не меняет глобально. Инлайновый `auto` оставлен: им пользуются якорные
   * ссылки внутри блока.
   */
  function установить(p) {
    state.progress = p;
    window.scrollTo({ top: Math.round(позиция(p)), behavior: "instant" });
  }

  /** Прошла ли тишина, по которой предыдущий жест считается законченным. */
  function тихо() {
    return performance.now() - последнийВвод > QUIET_MS;
  }

  /**
   * Новый жест: либо шагаем сразу, либо ставим в очередь глубиной один.
   *
   * ОЧЕРЕДЬ НУЖНА, ЧТОБЫ НЕПРЕРЫВНАЯ КРУТКА ДАВАЛА НЕПРЕРЫВНЫЙ ХОД. Жест,
   * пришедший посреди шага, раньше пропадал бесследно — читатель жал, а
   * страница молчала. Теперь он запоминается и берётся в тот же миг, когда шаг
   * закончился: пока читатель крутит, в очереди всегда что-то есть, и этапы
   * идут подряд без пауз.
   *
   * Глубина именно один. Правило «один жест — один этап» этим не нарушается:
   * прервать идущий шаг по-прежнему нельзя, он доигрывается целиком. А копить
   * жесты глубже незачем — за время шага читатель успевает передумать.
   */
  function принять(направление) {
    if (шаг) {
      очередь = направление;
      return;
    }
    шагнуть(направление);
  }

  /**
   * ВКЛАДКА УШЛА В ФОН ПОСРЕДИ ШАГА — ДОВОДИМ ЕГО СРАЗУ.
   *
   * В скрытой вкладке браузер не вызывает requestAnimationFrame, а на нём стоит
   * тикер GSAP. Твин шага замирает на том кадре, где его застали, и — главное —
   * не доходит до `onComplete`, то есть `шаг` не снимается никогда. Читатель
   * возвращается на вкладку и обнаруживает блок, который не отвечает на жесты
   * вовсе: `готов()` вечно ложно.
   *
   * Найдено не рассуждением, а на живой странице: панель браузера прятала
   * вкладку, и блок замирал ровно так. Сначала я принял это за поломку своей же
   * правки и полез искать её в другом месте.
   *
   * Доводим мгновенно, а не продолжаем: пока вкладки не было, показывать
   * анимацию всё равно было некому.
   */
  function наВидимость() {
    if (document.visibilityState === "visible" || !шаг) return;
    const цельШага = шаг.vars && шаг.vars.p;
    const добить = шаг.vars && шаг.vars.onComplete;
    шаг.kill();
    шаг = null;
    if (typeof цельШага === "number") установить(цельШага);
    if (добить) добить();
  }

  /* ────────────────────────────  ввод  ──────────────────────────── */

  /**
   * Запоминает направление хода. Разметка трогается только на СМЕНЕ стороны:
   * один мах тачпада даёт до шестидесяти событий в секунду, и переписывать
   * стрелку на каждом из них — это шестьдесят лишних правок DOM на ровном месте.
   */
  function запомнитьХод(направление) {
    if (направление === ходБыл) return;
    ходБыл = направление;
    показатьСторону();
  }

  /**
   * Колесо и тачпад.
   *
   * Событие перехватывается ТОЛЬКО пока блок держит экран и пока есть куда
   * шагать. На краях блока — вверху до первого этапа и внизу после последнего —
   * страница отпускается, иначе читатель оказался бы заперт в блоке.
   */
  function наКолесо(event) {
    if (!внутри() || event.ctrlKey) return;
    const направление = event.deltaY > 0 ? 1 : -1;
    запомнитьХод(направление);
    if (!цель(направление) && !шаг) {
      последнийВвод = 0;
      return;
    }
    event.preventDefault();
    /*
     * ЩЕЛЧОК КОЛЕСА — ВСЕГДА НОВЫЙ ЖЕСТ, даже если предыдущий был только что.
     *
     * Пока новизна жеста определялась одной тишиной, энергичный читатель с
     * мышью получал мёртвую страницу: замер на живой странице — 26 щелчков за
     * четыре секунды дали ОДИН этап, потому что каждое событие отодвигало
     * отсчёт тишины. Четыре спокойных щелчка давали четыре этапа. Для тачпада
     * тишина верна (мах — один жест), для колеса нет: там жест это щелчок.
     */
    const новыйЖест = Math.abs(event.deltaY) >= WHEEL_NOTCH || тихо();
    последнийВвод = performance.now();
    if (новыйЖест) принять(направление);
  }

  const ВПЕРЁД = ["ArrowDown", "PageDown", " ", "Spacebar"];
  const НАЗАД = ["ArrowUp", "PageUp"];

  /**
   * Клавиатура. Home, End и Tab не перехватываются намеренно: ими читатель
   * уходит из блока, и отнимать их — значит запереть его без выхода.
   */
  function наКлавишу(event) {
    if (!внутри() || event.altKey || event.ctrlKey || event.metaKey) return;
    const цельНаправления = ВПЕРЁД.includes(event.key)
      ? event.shiftKey && event.key === " "
        ? -1
        : 1
      : НАЗАД.includes(event.key)
        ? -1
        : 0;
    if (!цельНаправления) return;
    запомнитьХод(цельНаправления);
    if (!цель(цельНаправления) && !шаг) return;
    event.preventDefault();
    // Нажатие клавиши — всегда отдельный жест, как и щелчок колеса. Удержание
    // стрелки даёт повторы, и они выстраиваются в очередь: страница идёт
    // ступенями, а не молчит.
    последнийВвод = performance.now();
    принять(цельНаправления);
  }

  /* Касание: один свайп — один этап. */
  let палецY = 0;
  let палецВёл = false;

  function наКасание(event) {
    if (!внутри() || event.touches.length !== 1) return;
    палецY = event.touches[0].clientY;
    палецВёл = false;
  }

  function наДвижение(event) {
    if (!внутри() || event.touches.length !== 1) return;
    const dy = палецY - event.touches[0].clientY;
    const направление = dy > 0 ? 1 : -1;
    if (Math.abs(dy) >= TOUCH_THRESHOLD) запомнитьХод(направление);
    if (!цель(направление) && !шаг) return;
    // Родная прокрутка внутри блока отменяется целиком: иначе палец вёл бы
    // страницу параллельно шагу и они дрались бы за одну позицию.
    event.preventDefault();
    if (палецВёл || Math.abs(dy) < TOUCH_THRESHOLD) return;
    палецВёл = true;
    // Свайп — один жест на всё движение пальца: `палецВёл` не даст ему
    // сработать второй раз до отрыва.
    принять(направление);
    последнийВвод = performance.now();
  }

  /* ─────────────────────────  выход из блока  ───────────────────────── */

  /*
   * ВЫХОД ВЕДЁТ В ТУ СТОРОНУ, КУДА ЧИТАТЕЛЬ ШЁЛ. Первый заход сделал его
   * односторонним — всегда вниз, — и пришедший снизу вверх получал кнопку,
   * которая отправляла его туда, откуда он только что пришёл. Чтобы выбраться
   * наверх, ему оставались десять шагов назад: та же ловушка, только в другую
   * сторону.
   */
  /**
   * В какую сторону выпускать: 1 — вниз, −1 — вверх.
   *
   * НА КРАЯХ РЕШАЕТ ПОЛОЖЕНИЕ, А НЕ ПАМЯТЬ О ЖЕСТЕ, и это не перестраховка.
   * Направление залипает: читатель прошёл блок вниз, ушёл дальше по странице,
   * вернулся снизу — и получал стрелку вниз, то есть кнопку, отправляющую его
   * туда, откуда он только что пришёл. Поймано приёмкой, ручной прогон этого не
   * увидел, потому что шёл с чистой загрузки.
   *
   * Стоя в конце блока, пропускать можно только вверх — вниз там и так один
   * жест. В начале — наоборот. В середине верен последний жест, а если жестов
   * не было (пришёл по якорю, кнопкой «назад», ползунком) — ближний край.
   */
  function сторонаВыхода() {
    const p = state.progress;
    if (p >= 1 - AT_REST) return -1;
    if (p <= AT_REST) return 1;
    return ходБыл || (p > 0.5 ? -1 : 1);
  }

  function показатьСторону() {
    if (!выход) return;
    const сторона = сторонаВыхода();
    if (сторона === показано) return;
    показано = сторона;
    const вниз = сторона > 0;
    if (стрелка) стрелка.textContent = вниз ? "↓" : "↑";
    // Видимый текст один и тот же — он про действие. Куда именно ведёт кнопка,
    // сказано в её имени: стрелку скринридер не читает.
    выход.setAttribute(
      "aria-label",
      вниз
        ? "Пропустить анимацию и продолжить вниз по странице"
        : "Пропустить анимацию и вернуться выше по странице",
    );
  }

  /**
   * Прыжок за границу блока — мгновенный и без якоря.
   *
   * Целью служит не соседняя секция, а сама граница: экран ставится вплотную к
   * блоку с той стороны, куда читатель шёл. Так не нужно знать, что лежит
   * рядом, и правка соседних секций это не сломает.
   */
  function наВыход(event) {
    event.preventDefault();
    if (шаг) {
      шаг.kill();
      шаг = null;
    }
    const вниз = сторонаВыхода() > 0;
    const куда = вниз
      ? st.end + window.innerHeight
      : st.start - window.innerHeight;
    window.scrollTo({
      top: Math.max(0, Math.round(куда)),
      behavior: "instant",
    });
  }

  if (выход) {
    выход.addEventListener("click", наВыход);
    показатьСторону();
  }

  window.addEventListener("wheel", наКолесо, { passive: false });
  window.addEventListener("keydown", наКлавишу);
  window.addEventListener("touchstart", наКасание, { passive: true });
  window.addEventListener("touchmove", наДвижение, { passive: false });
  document.addEventListener("visibilitychange", наВидимость);

  /* ────────────────────────────  кадр  ──────────────────────────── */

  /** Возвращает true, если СОБРАННОСТЬ ДОМА изменилась с прошлого кадра. */
  function apply() {
    const progress = state.progress;

    if (progress !== lastAppliedProgress) {
      lastAppliedProgress = progress;
      houseChanged = false;
      applyGroups(progress, setGroup);
    } else {
      houseChanged = false;
    }

    cameraRig.update(progress);

    const index = activeStageIndex(progress);
    if (index !== lastAppliedIndex) {
      lastAppliedIndex = index;
      textSync.setStage(index);
    }

    return houseChanged;
  }

  return {
    apply,

    getProgress() {
      return state.progress;
    },

    /** Пересчёт границ секции после изменения раскладки. */
    refresh() {
      ScrollTrigger.refresh();
    },

    /**
     * Переход на этап по его номеру — мгновенно и без анимации.
     *
     * Этим ходят точки-кнопки: читатель выбрал, куда попасть, и показывать ему
     * пролёт через пропущенные этапы значило бы отнять то самое время, которое
     * он попросил не тратить. Идущий шаг снимается: две силы, тянущие одну
     * позицию прокрутки, дали бы рывок ровно того рода, от которого блок и
     * избавлялся.
     */
    goTo(index) {
      if (index < 0 || index >= REST.length) return;
      if (шаг) {
        шаг.kill();
        шаг = null;
      }
      последнийВвод = performance.now();
      установить(REST[index]);
    },

    /** Номер точки покоя — наружу ради приёмки. */
    restIndex: () => текущая(),

    /** Идёт ли шаг прямо сейчас. */
    stepping: () => !!шаг,

    destroy() {
      root.style.scrollBehavior = "";
      window.removeEventListener("wheel", наКолесо);
      window.removeEventListener("keydown", наКлавишу);
      window.removeEventListener("touchstart", наКасание);
      window.removeEventListener("touchmove", наДвижение);
      document.removeEventListener("visibilitychange", наВидимость);
      if (выход) выход.removeEventListener("click", наВыход);
      if (шаг) шаг.kill();
      st.kill();
    },
  };
}
