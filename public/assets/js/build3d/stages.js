/* ─────────────────────────  свет во времени прокрутки  ─────────────────────────
 *
 * ЗДЕСЬ РЕШЁН ПЕРВЫЙ ИЗ ТРЁХ ВОПРОСОВ ЭТАПА E — «время против прокрутки», в той
 * части, что касается света.
 *
 * В концепте обе доли выводились из секунд непрерывного прохода. На странице
 * прокрутка идёт рывками и может идти назад, поэтому обе доли пересчитаны в
 * доли прокрутки — состояние света остаётся ЧИСТОЙ ФУНКЦИЕЙ прогресса, и
 * обратный ход гасит вечер ровно тем же путём, каким его зажёг. По настенным
 * часам осталось только качание кресел: оно не состояние, а движение.
 *
 * Пропорции при этом те самые. Вечер выходит за `enter` десятого этапа — те же
 * 3.2 с из 48.8, — а собственный свет террасы разгорается ПОСЛЕ него, за
 * `COVE.ramp`. Порядок обязателен: лента включается в уже установившийся вечер,
 * иначе тёплый свет читается не событием, а частью заката.
 */

/** Десятый этап: единственный, у которого `evening`. */
const EVENING_STAGE = STAGES.find((stage) => stage.evening);

/** Разгон собственного света террасы в долях прокрутки. */
const TERRACE_START = EVENING_STAGE.enterEnd;
const TERRACE_SPAN = COVE.ramp / SCENARIO_SECONDS;

/**
 * Доля, на которой блок ЗАКАНЧИВАЕТ МЕНЯТЬСЯ: вечер установился, лента террасы
 * разгорелась, дальше до самого конца не происходит ничего.
 *
 * Нужна наружу, чтобы пошаговый ход останавливал читателя здесь, а не на
 * единице. Замер: между этой долей и концом блока лежат 372 px десктопной
 * прокрутки, на которых картинка неподвижна; шаг, ведущий до единицы, треть
 * своей длительности доигрывал вхолостую и всё это время держал ввод запертым.
 */
export const SCENE_SETTLED = TERRACE_START + TERRACE_SPAN;

/**
 * Две ЛИНЕЙНЫЕ доли, по которым `lighting.js` ведёт свет: переход в вечер и
 * разгон света террасы. Сглаженную ступень накладывает сам свет — кривая разгона
 * это его свойство, а не свойство сценария.
 */
export function lightMix(progress) {
  return {
    evening: clamp01(
      (progress - EVENING_STAGE.progressStart) /
        (EVENING_STAGE.enterEnd - EVENING_STAGE.progressStart),
    ),
    terrace: clamp01((progress - TERRACE_START) / TERRACE_SPAN),
  };
}

/**
 * Этап, который читает посетитель при текущем прогрессе.
 *
 * Граница ровно одна и это `progressStart` СЛЕДУЮЩЕГО этапа: текст меняется в
 * тот же момент, когда начинается выход в новый ракурс, а не когда предыдущий
 * этап дособрался. Иначе на выдержке читатель видел бы уже новый дом под старой
 * подписью — а весь смысл блока в том, что подпись объясняет то, что на экране.
 */
export function activeStageIndex(progress) {
  const p = clamp01(progress);
  for (let i = STAGES.length - 1; i >= 0; i--) {
    if (p >= STAGES[i].progressStart) return i;
  }
  return 0;
}

/* ─────────────────────────  сборка во времени прокрутки  ───────────────────────── */

/**
 * Локальный прогресс сборки внутри этапа: 0 — не начата, 1 — закончена.
 *
 * Считается по ВЫХОДУ, а не по всему отрезку этапа: остаток — выдержка, когда
 * дом уже собран и стоит неподвижно, пока читается текст. Без неё конструкция
 * достраивалась бы ровно до границы этапа, и остановка прокрутки почти в любой
 * точке заставала бы элементы на полпути.
 *
 * Доля выхода у каждого этапа своя и взята из таймингов концепта — от 5 : 3 на
 * первом такте до 2 : 3 на последнем. Прежняя сцена держала одну общую долю на
 * все этапы, и ритм превью при переносе потерялся бы.
 *
 * Функция чистая, поэтому прокрутка назад разбирает дом ровно тем же путём,
 * каким собрала: ничего не накапливается.
 */
export function stageProgress(stage, progress) {
  const span = stage.enterEnd - stage.progressStart;
  if (span <= 0) return progress >= stage.enterEnd ? 1 : 0;
  return clamp01((progress - stage.progressStart) / span);
}

/**
 * Состояние группы внутри этапа с учётом `offset`.
 *
 * Смещение необязательное: без него группа собирается за весь выход, поэтому
 * утверждённые кадры этапов, где несколько групп встают ВМЕСТЕ (05 и 07), не
 * меняются. Оно нужно там, где порядок задан смыслом, а не координатой: на
 * этапе 09 сначала настил, потом панель, вазон, стойки и только потом кресла —
 * опора обязана встать до того, что на ней висит.
 *
 * Остаток выхода растягивается на всю группу (деление на `1 − s`), иначе
 * смещённая группа не успела бы собраться к концу выхода.
 */
function groupProgress(stage, name, local) {
  const s = stage.offset && stage.offset[name] ? stage.offset[name] : 0;
  return s > 0 ? clamp01((local - s) / (1 - s)) : local;
}

/**
 * Состояние сборки всех групп при данном прогрессе.
 *
 * Живёт здесь, а не в `timeline.js`, потому что это сценарий, а не прокрутка:
 * `timeline.js` знает про ScrollTrigger и не обязан знать, что обноску снимают
 * на шестом этапе. Заодно правило становится проверяемым без GSAP.
 *
 * Этапы проходятся ПО ПОРЯДКУ, и это существенно. Группа может быть поставлена
 * одним этапом и снята другим — обноска встаёт на первом и уходит на шестом, —
 * и верным остаётся то состояние, которое написал ПОСЛЕДНИЙ распорядившийся ею
 * этап. Обратный порядок вернул бы обноску к готовому дому.
 */
const resolved = new Map();

export function applyGroups(progress, set) {
  /*
   * Сначала СВОДКА, потом применение, и каждой группе ровно одно значение.
   *
   * Раньше значения отдавались наружу прямо в обходе, и группа, которую один
   * этап ставит, а другой снимает, получала за кадр ДВЕ команды: обноску первый
   * такт ставил в единицу, а шестой тут же снимал в ноль. Пока состояние
   * применялось вслепую, это было незаметно; как только страница стала решать по
   * нему, пересчитывать ли теневую карту, признак «дом изменился» оказался
   * истинным ВСЕГДА после шестого этапа — то есть на большей половине блока
   * карта пересчитывалась каждый кадр впустую. Заодно сорок пять тел обноски
   * дважды за кадр раскладывались по местам.
   *
   * Сводка живёт на модуле, а не заводится на каждом кадре: кадров шестьдесят в
   * секунду, и мусорить в сборщик на ровном месте незачем.
   */
  resolved.clear();
  for (const stage of STAGES) {
    const local = stageProgress(stage, progress);
    for (const name of stage.objects)
      resolved.set(name, groupProgress(stage, name, local));
    /*
     * Временная конструкция снимается за то же время, за какое ставится
     * следующая: обратная прокрутка вернёт её тем же путём.
     *
     * Условие на начало этапа обязательно, и его цена — целая группа. До своего
     * этапа снятие НЕ ПРИМЕНЯЕТСЯ ВОВСЕ, иначе `1 − 0` объявляет группу
     * собранной с самого начала блока: обноска стояла готовой уже на нулевой
     * доле, первый этап переставал её ставить, и весь такт «участок и разметка»
     * показывал то, что зритель и так видел.
     */
    if (stage.removes && progress >= stage.progressStart) {
      for (const name of stage.removes) resolved.set(name, 1 - local);
    }
  }
  for (const [name, value] of resolved) set(name, value);
}

/**
 * Точки покоя: НАЧАЛО выдержки каждого этапа.
 *
 * Решение владельца от 2026-08-05, вариант (б) листа этапа F. Прежде целью была
 * СЕРЕДИНА выдержки, и это стоило дорого: замер аудита на живой странице
 * настоящим колесом — 16 остановок из 23, после которых страница ехала сама,
 * медиана добавки 316 px (40 % высоты окна), максимум 591.
 *
 * Начало выдержки — первый кадр, на котором этап ЗАКОНЧЕН: дом собран, камера
 * пришла на место (обе границы считаются от одного `enterEnd`). Замысел
 * «читатель всегда встаёт на законченном кадре» сохраняется целиком, а ехать до
 * него вдвое ближе.
 */
const REST_POINTS = STAGES.map((stage) => stage.enterEnd);

/**
 * Насколько близко к точке покоя считается «уже на месте».
 *
 * Нужен, чтобы притяжение не срабатывало от собственного результата: доехав до
 * точки, читатель обязан на ней остаться, иначе получается цепочка рывков.
 */
const REST_EDGE = 0.02;

/**
 * Куда доводить прокрутку после остановки.
 *
 * Притяжение срабатывает, только если читатель встал ПОСРЕДИ ВЫХОДА. Стоит он на
 * выдержке — возвращается его же позиция: тянуть человека из спокойного кадра
 * незачем, и именно это ощущалось как «страница едет сама».
 *
 * ЦЕЛЬ ВЫБИРАЕТСЯ ПО НАПРАВЛЕНИЮ ДВИЖЕНИЯ, А НЕ ПО РАССТОЯНИЮ. Это второй
 * заход: сперва бралась ближайшая точка, и стенд шага 0 сразу это отклонил.
 * Правило «ближайшая» РАЗРЫВНО ровно посередине каждого выхода — по разные
 * стороны от середины цели отличаются на целый этап. ScrollTrigger передаёт сюда
 * не текущую долю, а спроецированную по скорости, и она попадает в окрестность
 * этой середины постоянно: расхождение состояния между проходом вперёд и назад
 * подскочило с 8.23e-2 до 6.89e-1, то есть до двух третей длины блока.
 *
 * По направлению разрыва нет: обе стороны сходятся на границе этапа, где цели и
 * так совпадают. Заодно решается то, ради чего затевалось «ближайшая»: назад
 * доводка тянет только при движении назад. Замер аудита показывал, что PageUp
 * даёт −787 px, а притяжение добавляет +496 ПРОТИВ нажатия; теперь оно физически
 * не может пойти против направления читателя.
 *
 * Назад целью служит выдержка ПРЕДЫДУЩЕГО этапа, а не граница между ними: на
 * самой границе текст уже сменился на новый этап, а строить его ещё не начали, и
 * читатель остался бы с подписью про сваи над пустым участком.
 *
 * @param {number} progress доля, к которой ScrollTrigger предлагает довести
 * @param {object} [self] сам ScrollTrigger; из него берётся `direction`
 */
export function resolveSnap(progress, self) {
  const p = clamp01(progress);
  // Без ScrollTrigger (стенды, проверки) считаем движение вперёд: это то же
  // направление, в котором блок читают.
  const назадИдём = !!self && self.direction < 0;

  for (let i = 0; i < STAGES.length; i++) {
    const local = stageProgress(STAGES[i], p);
    // На законченном кадре и в его окрестности не трогаем вовсе.
    if (local <= REST_EDGE || local >= 1 - REST_EDGE) continue;

    if (!назадИдём) return REST_POINTS[i];
    // Назад: ближайший законченный кадр позади — выдержка предыдущего этапа.
    // До первого этапа её нет, там начало блока.
    return i > 0 ? REST_POINTS[i - 1] : STAGES[0].progressStart;
  }
  return p;
}

function clamp01(value) {
  return value < 0 ? 0 : value > 1 ? 1 : value;
}
