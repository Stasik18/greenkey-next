/**
 * Класс ввода: чем именно читатель крутит страницу.
 *
 * ЗАЧЕМ. Сглаживание сцены обязано быть разным для разных вводов, и это решение
 * владельца от 2026-08-04: единый коэффициент — компромисс не в ту сторону.
 * Колесо мыши даёт редкие крупные ступени, и без сглаживания дом собирался бы
 * рывками; тачпад даёт частый мелкий поток, у которого сглаживать нечего, и то
 * же значение читается там запаздыванием.
 *
 * ПРИЗНАК БЕРЁТСЯ ИЗ СИГНАЛА, А НЕ ИЗ ЯРЛЫКА УСТРОЙСТВА, и это не изящество.
 * Медиазапрос `pointer: coarse` тачпад ноутбука не ловит — у него точный
 * указатель, такой же, как у мыши. А система, сглаживающая колесо, выдаёт ровно
 * те же события `wheel`, что и тачпад. Нужной информации в ярлыке физически нет.
 *
 * ПОРОГИ ВЫВЕДЕНЫ ИЗ ЗАМЕРА НА ЖЕЛЕЗЕ ВЛАДЕЛЬЦА (2026-08-04, Chrome 151,
 * Windows, экран 1536 × 864 при плотности 1.25):
 *
 *                       тачпад              колесо мыши
 *   событий за 10 с     595 (59.5 Гц)       10 (1.0 Гц)
 *   шаг, медиана        6 px                100 px
 *   шаг, максимум       39 px               100 px
 *   мельче 20 px        94.4 %              0 %
 *   `wheelDelta` % 120  9 из 595            10 из 10
 *
 * Пересечения нет вовсе: между 39 и 100 пикселями пустота. Порог поставлен
 * посередине этой пустоты — 60 px.
 *
 * ЧЕГО ЗАМЕР НЕ ПОКАЗАЛ. Колесо, сглаженное САМОЙ СИСТЕМОЙ, на этой машине не
 * встретилось: Chrome отдавал сырые ступени по 100 px. Такое колесо по сигналу
 * неотличимо от тачпада — и это правильный ответ, а не беда: если система уже
 * растянула щелчок на кадры, прокрутка идёт плавно, и добавлять к ней сглаживание
 * не за чем. Замеры аудита давали такому вводу оптимум 0.12 против 0.06 у
 * тачпада, причём метрики хода между этими значениями не менялись.
 *
 * Сенсорного экрана на машине владельца нет (`maxTouchPoints: 0`), поэтому
 * константа касания взята из замеров аудита и на живом устройстве НЕ проверена.
 */

/**
 * Сглаживание прокрутки по классам, в секундах.
 *
 * Числа из замеров аудита: у колеса оптимум 0.30 (пик экранного шага падает со
 * 74…100 до 50…55 px, стоп-кадров с 39 % до 9 %), у тачпада — 0.06 (рывки с 4 %
 * до нуля, отставание с 35 до 21 px), у касания 0.18 остаётся как есть.
 *
 * КАСАНИЮ НУЖНО БОЛЬШЕ СГЛАЖИВАНИЯ, ЧЕМ ТАЧПАДУ, и это проверено: 0.05 на
 * касании хуже сразу по всем метрикам — пик 30 → 43 px, стоп-кадров 6 → 34 %.
 * Правило «раз это палец, значит отзывчивость» здесь неверно.
 *
 * Обнулять нельзя ни один: при нуле медианный шаг сцены равен нулю — половину
 * кадров картинка стоит, вторую прыгает.
 */
export const SCRUB_BY_INPUT = {
  wheel: 0.3,
  touchpad: 0.06,
  touch: 0.18,
};

/**
 * Класс по умолчанию — самый сглаженный.
 *
 * Ошибка в эту сторону стоит около 20 px отставания на первых двух событиях и
 * не видна; ошибка в другую — скачка на 74…90 px за кадр на первом же щелчке
 * колеса, и видна сразу.
 */
const DEFAULT_CLASS = "wheel";

/** Граница между «крупной ступенью» и «мелким потоком». Середина пустоты 39…100. */
const STEP_PX = 60;

/** Сколько последних событий смотрим и насколько старые уже не в счёт. */
const WINDOW_EVENTS = 10;
const WINDOW_MS = 1500;

/** Пауза, после которой поток событий считается новым жестом. */
const GESTURE_GAP_MS = 150;

/**
 * Сколько подтверждений нужно, чтобы УМЕНЬШИТЬ сглаживание.
 *
 * Правило несимметрично намеренно. Прибавка сглаживания сцену только замедляет и
 * скачка дать не может, поэтому применяется сразу. Убавка — наоборот: сделанная
 * посреди жеста, она отпускает накопленное отставание разом, и картинка прыгает.
 * Замер аудита на симметричном правиле: 214.8 px экранного шага за один кадр на
 * переключении. Поэтому убавка ждёт и границы жеста, и пяти подтверждений.
 */
const RELAX_CONFIRMATIONS = 5;

/** Насколько класс «сглаженнее» другого: по величине своей константы. */
const smoother = (a, b) => SCRUB_BY_INPUT[a] > SCRUB_BY_INPUT[b];

/**
 * Следит за вводом и сообщает, когда класс сменился.
 *
 * @param {(inputClass: string) => void} onChange вызывается только при СМЕНЕ
 * @returns {{ current: () => string, dispose: () => void }}
 */
export function createInputClass(onChange) {
  let current = DEFAULT_CLASS;
  let relaxSeen = 0;
  let lastEvent = 0;
  const steps = [];

  /**
   * @param {string} next класс, за который голосует поток прямо сейчас
   * @param {number} gap пауза ПЕРЕД этим событием; по ней узнаётся граница жеста
   */
  const apply = (next, gap) => {
    if (next === current) {
      relaxSeen = 0;
      return;
    }

    if (smoother(next, current)) {
      // Прибавляем сглаживание — можно сразу, посреди жеста: сцену это только
      // замедляет, скачка дать не может.
      current = next;
      relaxSeen = 0;
      onChange(current);
      return;
    }

    /*
     * Убавляем осторожно: голоса копим на каждом событии, а применяем только на
     * ГРАНИЦЕ ЖЕСТА. Пауза меряется ПЕРЕД событием, а не после — на этом я уже
     * ошибся: отметка последнего события обновлялась до проверки, зазор всегда
     * выходил нулевым, и ослабление не срабатывало ни разу за 595 событий
     * настоящего тачпада.
     */
    relaxSeen++;
    if (gap < GESTURE_GAP_MS || relaxSeen < RELAX_CONFIRMATIONS) return;
    current = next;
    relaxSeen = 0;
    onChange(current);
  };

  const onWheel = (event) => {
    const now = performance.now();
    // Пауза ПЕРЕД этим событием: именно она отделяет один жест от другого.
    const gap = lastEvent ? now - lastEvent : Infinity;
    // Строки прокрутки и страницы приводим к пикселям грубо: точность здесь не
    // нужна, нужен порядок величины, а он у строк и страниц заведомо крупный.
    const scale = event.deltaMode === 1 ? 16 : event.deltaMode === 2 ? 800 : 1;
    const step = Math.abs(event.deltaY) * scale;
    if (step > 0) {
      steps.push({ t: now, step });
      while (
        steps.length > WINDOW_EVENTS ||
        (steps.length && now - steps[0].t > WINDOW_MS)
      ) {
        steps.shift();
      }
    }
    lastEvent = now;

    // Одного события мало: первый щелчок колеса и первый мах по панели отличить
    // не по чему, и класс по умолчанию для этого и выбран.
    if (steps.length < 2) return;
    const sorted = steps.map((s) => s.step).sort((a, b) => a - b);
    const median = sorted[Math.floor(sorted.length / 2)];
    apply(median >= STEP_PX ? "wheel" : "touchpad", gap);
  };

  const onTouch = () => {
    lastEvent = performance.now();
    steps.length = 0;
    // Касание — не догадка по потоку, а факт: применяем сразу.
    apply("touch", Infinity);
  };

  // `passive` обязателен: слушатель ничего не отменяет, а без него браузер
  // вынужден ждать наш код, прежде чем прокрутить страницу.
  const opts = { passive: true, capture: true };
  window.addEventListener("wheel", onWheel, opts);
  window.addEventListener("touchstart", onTouch, opts);

  return {
    current: () => current,
    dispose() {
      window.removeEventListener("wheel", onWheel, opts);
      window.removeEventListener("touchstart", onTouch, opts);
    },
  };
}
