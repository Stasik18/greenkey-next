/**
 * Определение возможностей устройства и уровни качества сцены.
 *
 * Уровень выбирается один раз до создания рендерера, а затем может быть понижен
 * во время работы, если устройство не вытягивает кадр. Повышение не делается
 * намеренно: колебания качества туда-сюда заметнее, чем стабильно средний уровень.
 */

const TIER = {
  HIGH: "high",
  MEDIUM: "medium",
  LOW: "low",
  OFF: "off",
};

/** Порядок деградации: от лучшего к худшему. */
const TIER_ORDER = [TIER.HIGH, TIER.MEDIUM, TIER.LOW];

/*
 * У уровня три рычага, и разрешения теневой карты среди них НЕТ. Это замер, а не
 * упрощение (шаг 8 этапа E, 2026-08-04).
 *
 * Размер карты не меняет ни одного вызова отрисовки: на HIGH и MEDIUM их
 * одинаково 855. Не меняет он и времени кадра — при пересчёте карты КАЖДЫЙ кадр
 * медиана на десктопе 28.6 мс при 2048, 29.6 при 1024 и 28.9 при 768, то есть
 * 2048 оказалась даже быстрее остальных; в портрете разброс 26.6 / 25.1 / 23.6.
 *
 * Дорога сама ТЕНЬ, а не её точность: без неё 20.1 мс на десктопе и 12.1 в
 * портрете, то есть теневой проход стоит 8.5 и 14.5 мс. Поэтому нижняя ступень
 * лестницы — «тени нет», и туда же watchdog уводит устройство, которое не тянет
 * кадр. А пока тень есть, она обязана быть ВЕРНОЙ: тексель равен
 * 2·SHADOW.extent/mapSize, вся приёмка снята на паре 11/2048 (1.07 см), и
 * прежние 768 давали 2.86 см — грубее того значения, на котором замер концепта
 * ловил кляксы по кромкам до 3 % кадра. Размер живёт в `SHADOW` и здесь его нет.
 *
 * `detail` тоже убран: его не читал никто с тех пор, как геометрия переехала в
 * `house.js`. Поле конфигурации, которое ничего не значит, хуже отсутствующего.
 * Заводить тиры детализации не понадобилось — пик 855 при потолке 897.
 *
 * ЧТО ИЗ ЭТОГО РАБОТАЕТ ТОЛЬКО ПРИ ЗАПУСКЕ. `antialias` задаётся при создании
 * контекста WebGL и после этого не меняется ничем — понижение уровня на лету его
 * не снимет. Замер это подтверждает и заодно доказывает, что ВСЁ ОСТАЛЬНОЕ
 * понижение переносит точно: понижённая с HIGH сцена и запущенная сразу на LOW
 * различаются на 50 932 пикселя, а с тем же сглаживанием — на НОЛЬ.
 */
const PROFILES = {
  [TIER.HIGH]: {
    maxPixelRatio: 2,
    shadows: true,
    antialias: true,
  },
  /*
   * СРЕДНЯЯ СТУПЕНЬ ПОЛУЧИЛА СОБСТВЕННЫЙ РЫЧАГ (решение владельца 2026-08-05).
   *
   * До этого её потолок плотности стоял на 1.5 — выше типичной фактической
   * плотности экрана, и потому не связывал вообще ничего: тени те же, сглаживание
   * то же, ни одного отличия от верхней ступени. Замер аудита: HIGH против MEDIUM
   * различаются на 0.95 % кадра, то есть в шуме, тогда как HIGH против LOW — на
   * 7.91 %. Лестница тратила на пустую ступень полтора-два окна наблюдения и
   * съезжала на нижнюю, где картинка беднеет по-настоящему.
   *
   * Единица — настоящий рычаг: на экране владельца (плотность 1.25) буфер падает
   * с 1.77 до 1.13 мегапикселя, а число пикселей буфера — одна из всего двух
   * статей такта кадра, найденных замером. Тени и свет при этом остаются.
   */
  [TIER.MEDIUM]: {
    maxPixelRatio: 1,
    shadows: true,
    antialias: true,
  },
  [TIER.LOW]: {
    maxPixelRatio: 1,
    shadows: false,
    antialias: false,
  },
};

/** Нижняя граница памяти и потоков, ниже которой сцена идёт в упрощённом виде. */
const WEAK_DEVICE_MEMORY_GB = 4;
const WEAK_DEVICE_CORES = 4;
/** Граница, ниже которой WebGL не запускается вовсе. */
const MINIMUM_MEMORY_GB = 2;
const MINIMUM_CORES = 3;

function prefersReducedMotion() {
  return window.matchMedia("(prefers-reduced-motion: reduce)").matches;
}

/**
 * Итоговый профиль качества. TIER.OFF означает, что 3D не запускается вовсе
 * и на странице остаётся исходная SVG-версия блока.
 *
 * Наличие WebGL здесь намеренно НЕ проверяется. Пробный контекст стоил от 70
 * до 360 мс блокировки главного потока — первый WebGL-контекст во вкладке
 * синхронно ждёт инициализации драйвера, — и платили за это все посетители
 * ровно в окне отрисовки первого экрана. Отсутствие WebGL всплывёт само при
 * создании настоящего рендерера, а этот путь уже возвращает блок к SVG-версии.
 */
export function detectQuality() {
  if (prefersReducedMotion()) return profileFor(TIER.OFF, "reduced-motion");

  const memory = navigator.deviceMemory;
  const cores = navigator.hardwareConcurrency;
  // Планшет с трекпадом не даёт coarse-указателя и получал уровень для
  // десктопа — с буфером в пять с половиной мегапикселей.
  const isTouch =
    window.matchMedia("(pointer: coarse)").matches ||
    navigator.maxTouchPoints > 0;

  // Совсем слабое устройство 3D не получает вовсе: там дешевле и честнее
  // оставить SVG-версию, чем показывать упрощённую сцену на десяти кадрах.
  const isMinimal =
    (typeof memory === "number" && memory <= MINIMUM_MEMORY_GB) ||
    (typeof cores === "number" && cores <= MINIMUM_CORES);
  if (isMinimal) return profileFor(TIER.OFF, "minimal-device");

  const isWeak =
    (typeof memory === "number" && memory < WEAK_DEVICE_MEMORY_GB) ||
    (typeof cores === "number" && cores < WEAK_DEVICE_CORES);

  if (isWeak) return profileFor(TIER.LOW, "weak-device");
  if (isTouch) return profileFor(TIER.MEDIUM, "touch-device");
  return profileFor(TIER.HIGH, "default");
}

function profileFor(tier, reason) {
  if (tier === TIER.OFF) return { tier, reason, enabled: false };
  return { tier, reason, enabled: true, ...PROFILES[tier] };
}

/** Следующий уровень вниз или null, если понижать уже некуда. */
export function nextTierDown(tier) {
  const index = TIER_ORDER.indexOf(tier);
  if (index < 0 || index === TIER_ORDER.length - 1) return null;
  return profileFor(TIER_ORDER[index + 1], "runtime-downgrade");
}

/**
 * Потолок по числу пикселей буфера отрисовки.
 *
 * Одного ограничения плотности мало: канвас занимает всю секцию, и на
 * 27-дюймовом мониторе с удвоенной плотностью сцена рисовалась бы в 14.7
 * мегапикселя — в одиннадцать раз больше, чем на ноутбуке, при том же числе
 * вызовов отрисовки. Заполнение, а не геометрия, и было причиной провалов
 * кадра на больших экранах.
 */
const MAX_DRAWING_PIXELS = 2_800_000;

/** Пиксельная плотность с учётом потолка профиля — главный рычаг на мобильных. */
export function resolvePixelRatio(profile, cssWidth, cssHeight) {
  const ratio = Math.min(window.devicePixelRatio || 1, profile.maxPixelRatio);
  const area = (cssWidth || 0) * (cssHeight || 0);
  if (area <= 0) return ratio;
  return Math.min(ratio, Math.sqrt(MAX_DRAWING_PIXELS / area));
}

/** Окно наблюдения задано временем, а не числом кадров: на устройстве,
 *  которое едва тянет 10 FPS, окно в 60 кадров растянулось бы на шесть секунд
 *  и качество упало бы уже после того, как читатель успел всё увидеть. */
const WATCHDOG_WINDOW_MS = 1500;

/**
 * Порог «медленного» кадра.
 *
 * БЫЛО 22 мс (~45 к/с), И ЭТО ОКАЗАЛОСЬ САМЫМ НЕУДАЧНЫМ МЕСТОМ НА ШКАЛЕ. Такт
 * кадра квантуется интервалом синхронизации экрана, промежуточных значений не
 * бывает. На мониторе владельца (163.9 Гц, такт 6.1 мс) наблюдаемый ряд такой:
 *
 *   6.1   12.2   18.3   24.4   30.5   36.6
 *
 * Здоровый блок идёт по 18.3, а под настоящим колесом поднимается ровно на один
 * интервал — до 24.4. Порог 22 лежал между этими двумя значениями, то есть
 * срабатывал от одного лишнего тика на совершенно здоровом кадре. Замер аудита:
 * под настоящим вводом лестница съезжала до самого низа за 7.5…12.2 секунды, а
 * нижняя ступень стоит 7.91 % кадра — читатель платил четвертью видимого
 * качества за то, что сцена шла 41 к/с вместо 55.
 *
 * СТАЛО 35 мс (~29 к/с), и это ЧИСЛО ВРЕМЕНИ, А НЕ ДОЛЯ ТАКТА. План этапа F
 * предлагал считать порог относительно такта устройства, но восприятие рывка
 * абсолютно: 41 к/с выглядит одинаково и на экране 60 Гц, и на 165 Гц. Менять
 * надо было не единицу измерения, а само значение — прежнее было выбрано без
 * оглядки на цену понижения.
 *
 * Куда попадает новое значение на разных экранах:
 *
 *   60 Гц    ряд 16.7  33.3  50.0    — 33.3 (один пропущенный кадр) НЕ роняет,
 *                                      50.0 роняет, и его же ловит критический порог
 *   120 Гц   ряд 16.6  24.9  33.2    — 33.2 не роняет, 41.5 роняет
 *   165 Гц   ряд 18.3  24.4  30.5    — здоровый и «плюс тик» не роняют, 36.6 роняет
 *
 * То есть на всех трёх порог стоит в промежутке между «работает нормально» и
 * «действительно плохо», а не внутри рабочего диапазона.
 */
const SLOW_FRAME_MS = 35;
const SLOW_WINDOWS_BEFORE_DOWNGRADE = 2;
/**
 * Минимум кадров в окне. Без него одна долгая пауза — например, стойло на
 * линковке шейдера — закрывает окно единственным семплом, и медиана этого
 * окна равна длине паузы. Два таких подряд роняли качество на устройстве,
 * которое на самом деле держит кадр.
 */
const MIN_WINDOW_FRAMES = 20;
/** Медиана, при которой понижаемся немедленно, не дожидаясь второго окна. */
const CRITICAL_FRAME_MS = 50; // 20 FPS
/** Пауза после старта и после каждого понижения: это заведомо долгие кадры. */
const WARMUP_MS = 1500;
const AFTER_DOWNGRADE_MS = 500;

/**
 * Наблюдатель за временем кадра. Считает медиану по окну, а не среднее:
 * одиночный долгий кадр при компиляции шейдеров не должен ронять качество сцены.
 */
export function createPerformanceWatchdog(onSlow) {
  let frames = [];
  let windowMs = 0;
  let slowWindows = 0;
  let disabled = false;
  let skipMs = WARMUP_MS;

  const reset = () => {
    frames = [];
    windowMs = 0;
  };

  return {
    sample(deltaMs) {
      if (disabled) return;

      // Прогрев и первые кадры после смены качества не считаем: там линкуются
      // шейдеры и пересоздаётся теневая карта, кадры заведомо длинные.
      if (skipMs > 0) {
        skipMs -= deltaMs;
        return;
      }

      frames.push(deltaMs);
      windowMs += deltaMs;
      if (windowMs < WATCHDOG_WINDOW_MS || frames.length < MIN_WINDOW_FRAMES)
        return;

      const sorted = frames.slice().sort((a, b) => a - b);
      const median = sorted[Math.floor(sorted.length / 2)];
      reset();

      if (median <= SLOW_FRAME_MS) {
        slowWindows = 0;
        return;
      }

      slowWindows += 1;
      // На совсем неподъёмном кадре ждать второе окно нельзя: полторы секунды
      // на понижение — это половина блока, показанная в двадцати кадрах.
      if (
        median < CRITICAL_FRAME_MS &&
        slowWindows < SLOW_WINDOWS_BEFORE_DOWNGRADE
      )
        return;

      slowWindows = 0;
      skipMs = AFTER_DOWNGRADE_MS;
      onSlow(median);
    },
    stop() {
      disabled = true;
      reset();
    },
  };
}
