export function createCameraRig(THREE) {
  const camera = new THREE.PerspectiveCamera(FOV, 1, NEAR, FAR);

  const desiredPosition = new THREE.Vector3();
  const desiredTarget = new THREE.Vector3();
  const currentTarget = new THREE.Vector3();

  // Последовательность состояний: нулевое — общий вид до начала строительства.
  /*
   * Маршрут пересобирается при смене соотношения сторон, а не запоминается один
   * раз: поворот телефона обязан перекомпоновать кадр без перезагрузки. Набор
   * выбирается тем же порогом, что и в концепте.
   */
  let states = STATES;
  let route = buildRoute(states);

  function buildRoute(set) {
    return [set.establishing, ...STAGES.map((stage) => set[stage.camera])];
  }

  function pickSet(nextAspect) {
    const next =
      nextAspect < PORTRAIT_MAX_ASPECT ? SET.portrait : SET.landscape;
    if (next === states) return;
    states = next;
    route = buildRoute(states);
  }

  let aspect = REFERENCE_ASPECT;
  let distanceScale = 1;
  let verticalBias = 0;
  let horizontalBias = 0;

  /*
   * Последняя применённая доля. Нужна ровно затем, чтобы после пересчёта таблиц
   * экранного пути вернуть камеру туда, где она стояла: построение таблицы
   * гоняет камеру по всему маршруту, и без возврата первый же кадр после смены
   * раскладки показал бы чужой ракурс.
   */
  let lastProgress = 0;

  function place(azimuth, elevation, distance, target) {
    const az = azimuth * DEG;
    const el = elevation * DEG;
    const radius = distance * distanceScale;

    // Опускаем весь кадр: камера и точка интереса едут вниз на одну величину,
    // поэтому дом поднимается в кадре, а ракурс остаётся прежним.
    const frameHeight = 2 * radius * Math.tan((FOV / 2) * DEG);
    const biasTaper = clamp01(
      (radius - BIAS_NEAR_DISTANCE) / (BIAS_FULL_DISTANCE - BIAS_NEAR_DISTANCE),
    );
    desiredTarget.set(
      target[0],
      target[1] - frameHeight * verticalBias * biasTaper,
      target[2],
    );

    // Смещение кадра вбок: на широком экране текст этапа занимает левую
    // колонку, поэтому дом уводится вправо от центра. Камера и точка интереса
    // едут по горизонтали камеры на одну величину, ракурс не меняется.
    if (horizontalBias !== 0) {
      const shift = frameHeight * aspect * horizontalBias;
      desiredTarget.x -= Math.cos(az) * shift;
      desiredTarget.z += Math.sin(az) * shift;
    }

    desiredPosition.set(
      desiredTarget.x + radius * Math.cos(el) * Math.sin(az),
      desiredTarget.y + radius * Math.sin(el),
      desiredTarget.z + radius * Math.cos(el) * Math.cos(az),
    );
  }

  /** Расчётное положение камеры для прогресса без учёта сглаживания. */
  function resolve(progress) {
    const p = clamp01(progress);
    let index = STAGES.length - 1;
    for (let i = 0; i < STAGES.length; i++) {
      if (p <= STAGES[i].progressEnd || i === STAGES.length - 1) {
        index = i;
        break;
      }
    }

    /*
     * Камера идёт к ракурсу этапа за его ВЫХОД и дальше стоит на выдержке —
     * так же, как собирается дом, и по той же границе `enterEnd`.
     *
     * Пока движение было растянуто на весь отрезок этапа, камера не
     * останавливалась НИ РАЗУ за весь блок: выдержки не существовало, и
     * требование сценария «60–70 % на действие, 15–20 % на замедление»
     * выполнялось только в превью концепта. Читать текст под непрерывно едущим
     * кадром — ровно то, ради чего выдержка и придумана.
     */
    /*
     * Доля выхода берётся у сценария, а не считается заново. Формула здесь
     * повторялась построчно, и это ровно тот случай, из-за которого в проекте
     * заведено правило одного источника: правка границы этапа в одном месте
     * молча разошлась бы с камерой.
     */
    placeStage(index, paceEase(index, stageProgress(STAGES[index], p)));
  }

  /** Постановка камеры в положение `u` пути такта, без всяких кривых. */
  function placeStage(index, u) {
    const from = route[index];
    const to = route[index + 1];
    place(
      mix(from.azimuth, to.azimuth, u),
      mix(from.elevation, to.elevation, u),
      mix(from.distance, to.distance, u),
      [
        mix(from.target[0], to.target[0], u),
        mix(from.target[1], to.target[1], u),
        mix(from.target[2], to.target[2], u),
      ],
    );
  }

  function applyPlaced() {
    camera.position.copy(desiredPosition);
    currentTarget.copy(desiredTarget);
    camera.lookAt(currentTarget);
  }

  /* ───────────────────  таблица экранного пути такта  ─────────────────── */

  const paceProbes = PACE_POINTS.map((p) => new THREE.Vector3(...p));
  const paceNdc = new THREE.Vector3();
  const paceA = new Float64Array(paceProbes.length * 2);
  const paceB = new Float64Array(paceProbes.length * 2);
  const paceWA = new Float64Array(paceProbes.length);
  const paceWB = new Float64Array(paceProbes.length);
  let pace = null;

  /**
   * Экранные координаты контрольных точек при положении `u` пути такта.
   *
   * По горизонтали координата домножается на соотношение сторон: NDC меряет
   * половинами кадра, и без этого узкий кадр считал бы горизонтальный ход
   * наравне с вертикальным.
   *
   * Вместе с координатами считается ВЕС точки — насколько она в кадре. Разбор
   * при `VIS_FULL`.
   */
  function paceShot(index, u, out, weight) {
    placeStage(index, u);
    applyPlaced();
    camera.updateMatrixWorld(true);
    for (let k = 0; k < paceProbes.length; k++) {
      paceNdc.copy(paceProbes[k]).project(camera);
      out[k * 2] = paceNdc.x * aspect;
      out[k * 2 + 1] = paceNdc.y;
      weight[k] =
        paceNdc.z > -1 && paceNdc.z < 1
          ? visAxis(paceNdc.x) * visAxis(paceNdc.y)
          : 0;
    }
  }

  /** Экранный ход между двумя кадрами: среднее по точкам с весом видимости. */
  function paceMove(a, wa, b, wb) {
    let sum = 0;
    let total = 0;
    for (let k = 0; k < paceProbes.length; k++) {
      const w = (wa[k] + wb[k]) / 2;
      if (w <= 0) continue;
      sum += w * Math.hypot(b[k * 2] - a[k * 2], b[k * 2 + 1] - a[k * 2 + 1]);
      total += w;
    }
    if (total > 0) return sum / total;
    // В кадре нет ни одной точки — берём все поровну, иначе такт остался бы
    // без таблицы вовсе.
    let plain = 0;
    for (let k = 0; k < paceProbes.length; k++) {
      plain += Math.hypot(b[k * 2] - a[k * 2], b[k * 2 + 1] - a[k * 2 + 1]);
    }
    return plain / paceProbes.length;
  }

  /**
   * Пересчёт таблиц. Зовётся на смене раскладки, а не на кадре: экранный путь
   * зависит от соотношения сторон, отодвигания камеры и смещений кадра, и все
   * три меняются только там.
   */
  function buildPace() {
    pace = STAGES.map((stage, i) => {
      const cum = new Float64Array(PACE_STEPS + 1);
      paceShot(i, 0, paceA, paceWA);
      for (let j = 1; j <= PACE_STEPS; j++) {
        paceShot(i, j / PACE_STEPS, paceB, paceWB);
        cum[j] = cum[j - 1] + paceMove(paceA, paceWA, paceB, paceWB);
        paceA.set(paceB);
        paceWA.set(paceWB);
      }
      const total = cum[PACE_STEPS];
      // Такт, в котором камера не двигается вовсе (первый — там работает одна
      // разметка), таблицы не получает: делить нечего.
      if (total < 1e-9) return null;
      for (let j = 0; j <= PACE_STEPS; j++) cum[j] /= total;
      return cum;
    });
    resolve(lastProgress);
    applyPlaced();
  }

  /**
   * Кривая выхода такта: сначала полка задаёт, какую долю ЭКРАННОГО пути дом
   * должен пройти к этому моменту, потом таблица переводит её в положение на
   * пути камеры.
   */
  function paceEase(index, t) {
    const a = shelf(clamp01(t));
    const table = pace && pace[index];
    if (!table) return a;

    let lo = 0;
    let hi = PACE_STEPS;
    while (hi - lo > 1) {
      const mid = (lo + hi) >> 1;
      if (table[mid] <= a) lo = mid;
      else hi = mid;
    }
    const span = table[hi] - table[lo];
    return (lo + (span > 1e-12 ? (a - table[lo]) / span : 0)) / PACE_STEPS;
  }

  /*
   * Первичная постановка. Стоит здесь, а не выше по файлу, потому что
   * `buildPace` опирается на объявленные рядом таблицы: вызов до них попадал бы
   * во временную мёртвую зону и падал бы на загрузке.
   */
  buildPace();

  return {
    camera,

    /**
     * Камера идёт ЗА долей прокрутки без собственного сглаживания: доля приходит
     * уже сглаженной, и второй фильтр поверх неё только добавлял задержку.
     */
    update(progress) {
      lastProgress = progress;
      resolve(progress);
      applyPlaced();
    },

    /**
     * Мгновенная установка. Отличается от `update` только именем: у камеры своего
     * состояния между кадрами не осталось, и догонять ей нечего. Имя сохранено —
     * на местах вызова оно говорит «поставить сразу», и это по-прежнему правда.
     */
    snap(progress) {
      this.update(progress);
    },

    resize(width, height) {
      aspect = width / Math.max(height, 1);
      pickSet(aspect);
      camera.aspect = aspect;
      // Набор уже выбран выше, поэтому здесь известно, компенсировать узкий
      // кадр дистанцией или он уже скомпонован под него.
      distanceScale =
        states === SET.portrait
          ? PORTRAIT_DISTANCE_SCALE
          : clamp(REFERENCE_ASPECT / aspect, 1, MAX_DISTANCE_SCALE);
      verticalBias =
        PORTRAIT_BIAS *
        clamp01(
          (BIAS_FROM_ASPECT - aspect) / (BIAS_FROM_ASPECT - BIAS_TO_ASPECT),
        );
      horizontalBias =
        LANDSCAPE_BIAS *
        clamp01(
          (aspect - BIAS_FROM_ASPECT) /
            (LANDSCAPE_FULL_ASPECT - BIAS_FROM_ASPECT),
        );
      camera.updateProjectionMatrix();
      // Строго после матрицы проекции: экранный путь меряется ею же.
      buildPace();
    },
  };
}

/** Вес точки по одной оси кадра: единица в кадре, ноль за кромкой, гладко между. */
function visAxis(value) {
  const a = Math.abs(value);
  if (a <= VIS_FULL) return 1;
  if (a >= VIS_GONE) return 0;
  const t = (VIS_GONE - a) / (VIS_GONE - VIS_FULL);
  return t * t * (3 - 2 * t);
}

function mix(from, to, t) {
  return from + (to - from) * t;
}

function clamp(value, min, max) {
  return value < min ? min : value > max ? max : value;
}

function clamp01(value) {
  return clamp(value, 0, 1);
}
