/**
 * Доля выхода, за которую камера разгоняется до полной скорости и тормозится.
 *
 * Превышение пика над средней скоростью равно 1/(1 − RAMP) и выходит ровно
 * теоретическим: 0.25 → 1.34, 0.10 → 1.11, 0.05 → 1.05. По одному этому числу
 * разгон хотелось бы взять как можно короче, но дальше 0.10 отдача кончается
 * (максимум по блоку 2.34 → 2.29 → 2.21), а платить приходится тем, ради чего
 * кривая и заведена: при 0.05 камера набирает полную скорость за двадцатую
 * часть выхода, то есть трогается почти рывком.
 */
const RAMP = 0.1;

/** ∫₀^u от `smoothstep`: разгон и торможение остаются такими же гладкими. */
const intS = (u) => u * u * u - (u * u * u * u) / 2;

/** Кривая выхода: разгон, полка, торможение. На границах скорость нулевая. */
function shelf(t) {
  const norm = 1 - RAMP;
  if (t < RAMP) return (RAMP * intS(t / RAMP)) / norm;
  if (t > 1 - RAMP) return (norm - RAMP * intS((1 - t) / RAMP)) / norm;
  return (t - RAMP / 2) / norm;
}

